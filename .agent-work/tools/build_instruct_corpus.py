#!/usr/bin/env python3
"""Build a compact instruction corpus for generative fine-tuning.

The transformer learns from dialogue examples, not from a lookup table. This
script merges the curated conversation corpus (data/chat.txt) with the
Minecraft wiki question/answer corpus (data/mc_qa.txt), shortens very long
wiki answers, and adds a few multi-turn follow-up examples so the model can
use the conversation history.

Output: data/instruct.txt
"""
import os
import re
import sys

CHAT = "data/chat.txt"
QA = "data/mc_qa.txt"
OUT = "data/instruct.txt"

HEADER = """*** ULTRON INSTRUCTION CORPUS ***
Generative chat fine-tuning examples for English grammar and Minecraft.
Generated by .agent-work/tools/build_instruct_corpus.py. Do not edit by hand.

"""

MAX_ANSWER_CHARS = 320
MAX_ANSWER_SENTENCES = 2


def clean(text):
    text = text.replace("\u00a0", " ")
    text = re.sub(r"\s+", " ", text).strip()
    return text


def shorten(text):
    text = clean(text)
    parts = re.split(r"(?<=[.!?])\s+", text)
    kept = []
    for part in parts:
        part = part.strip()
        if not part:
            continue
        if kept and len(" ".join(kept + [part])) > MAX_ANSWER_CHARS:
            break
        kept.append(part)
        if len(kept) >= MAX_ANSWER_SENTENCES:
            break
    if not kept:
        kept = [text[:MAX_ANSWER_CHARS].rstrip()]
    out = " ".join(kept).strip()
    if len(out) > MAX_ANSWER_CHARS:
        out = out[:MAX_ANSWER_CHARS - 3].rstrip() + "..."
    if out and out[-1] not in ".!?":
        out += "."
    return out


def read_pairs(path):
    pairs = []
    if not os.path.exists(path):
        return pairs
    question = None
    memory = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("memory: "):
                memory = line[8:].strip()
            elif line.startswith("user: "):
                question = line[6:].strip()
            elif line.startswith("ultron: ") and question is not None:
                pairs.append((memory, question, line[8:].strip()))
                question = None
                memory = None
            elif not line.strip():
                question = None
                memory = None
    return pairs


def topic_of(question):
    q = question.lower().strip().rstrip("?.!")
    patterns = [
        (r"^what(?:'s| is) (.+)$", "what"),
        (r"^tell me about (.+)$", "what"),
        (r"^describe (.+)$", "what"),
        (r"^how (?:do|can) i (?:get|obtain|find) (.+)$", "get"),
        (r"^where (?:do|can) i find (.+)$", "get"),
        (r"^how (?:do|can) i (?:craft|make) (.+)$", "craft"),
        (r"^how to (?:craft|make) (.+)$", "craft"),
        (r"^what is the recipe for (.+)$", "craft"),
        (r"^(?:can|is) (.+?) (?:be )?craft(?:ed|able).*$", "craftable"),
    ]
    for pattern, kind in patterns:
        m = re.match(pattern, q)
        if m:
            return m.group(1).strip(), kind
    return None, None


def write_pair(f, memory, question, answer):
    if memory:
        f.write("memory: %s\n" % memory)
    f.write("user: %s\n" % question)
    f.write("ultron: %s\n\n" % answer)


def main():
    pairs = []
    seen = set()
    for path in (CHAT, QA):
        for memory, question, answer in read_pairs(path):
            if not question or not answer:
                continue
            answer = shorten(answer)
            key = (memory, question.lower(), answer)
            if key in seen:
                continue
            seen.add(key)
            pairs.append((memory, question, answer))

    # Follow-up examples teach the model to use the previous turn when the
    # user says "it" or "that".
    by_topic = {}
    for memory, question, answer in pairs:
        if memory:
            continue
        topic, kind = topic_of(question)
        if not topic:
            continue
        by_topic.setdefault(topic, {})[kind] = answer

    followups = []
    for topic, kinds in by_topic.items():
        first = kinds.get("what")
        second = kinds.get("craft") or kinds.get("get") or kinds.get("craftable")
        if not first or not second:
            continue
        history = ["user: what is %s" % topic]
        followups.append((history, "and how can i craft it", second))
        followups.append((history, "and how can i get it", kinds.get("get") or second))

    # A tiny amount of memory training so facts in the prompt can be copied.
    memory_examples = []
    for name in ("alex", "mikailamin", "sam", "jordan"):
        memory_examples.append(
            ("ultron remembers: name is %s" % name, "what is my name?", "your name is %s." % name)
        )
    memory_examples.append(
        ("ultron remembers: likes is chess", "what do i like?", "you like chess.")
    )
    memory_examples.append(
        ("ultron remembers: likes is minecraft", "what do i like?", "you like minecraft.")
    )

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(HEADER)
        for memory, question, answer in pairs:
            write_pair(f, memory, question, answer)
        for history, question, answer in followups:
            for line in history:
                f.write("memory: %s\n" % line)
            f.write("user: %s\n" % question)
            f.write("ultron: %s\n\n" % answer)
        for memory, question, answer in memory_examples:
            write_pair(f, memory, question, answer)

    print("wrote %s: %d pairs, %d bytes" % (OUT, len(pairs) + len(followups) + len(memory_examples),
                                            os.path.getsize(OUT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Build the conversational training corpus from data/chat_kb.tsv.

The knowledge base is the single source of truth for curated chatbot answers.
This script turns it into the "user:" / "ultron:" dialogue format that the
Ultron tokenizer and Chat CLI both understand. Re-run it whenever the TSV
changes:

    python3 .agent-work/tools/build_chat_corpus.py

Output: data/chat.txt
"""
import os
import sys

SRC = "data/chat_kb.tsv"
OUT = "data/chat.txt"

HEADER = """*** ULTRON CONVERSATION CORPUS ***
Dialogue examples for English grammar, writing, and Minecraft Java Edition.
Generated from data/chat_kb.tsv by .agent-work/tools/build_chat_corpus.py.
Do not edit this file by hand.

"""


def main():
    if not os.path.exists(SRC):
        sys.stderr.write("missing %s\n" % SRC)
        return 1

    entries = []
    with open(SRC, encoding="utf-8") as f:
        for line_no, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) < 3:
                sys.stderr.write("skipping malformed line %d\n" % line_no)
                continue
            category, question, answer = parts[0], parts[1], "\t".join(parts[2:])
            question, answer = question.strip(), answer.strip()
            if question and answer:
                entries.append((category.strip(), question, answer))

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(HEADER)
        last = None
        for category, question, answer in entries:
            if category != last:
                f.write("===== %s =====\n\n" % category)
                last = category
            f.write("user: %s\n" % question)
            f.write("ultron: %s\n\n" % answer)

    print("wrote %s: %d turns, %d bytes" % (OUT, len(entries), os.path.getsize(OUT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

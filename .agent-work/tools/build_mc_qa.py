#!/usr/bin/env python3
"""Turn the Minecraft wiki extracts into instruction/chat training data.

The plain-text corpus in data/mc.txt is useful for language modelling, but a
chat assistant also needs question/answer pairs. This script reads the same
extracts and derives grounded questions for every article: definitions,
obtaining, crafting, usage, and natural generation. The result uses the
"user:" / "ultron:" turn format understood by the tokenizer and Chat CLI.

Usage:
    python3 .agent-work/tools/build_mc_qa.py

Output: data/mc_qa.txt
"""
import os
import re
import sys

SRC = "data/mc.txt"
OUT = "data/mc_qa.txt"

HEADER = """*** ULTRON MINECRAFT INSTRUCTION CORPUS ***
Question/answer pairs derived from minecraft.wiki article extracts.
Generated by .agent-work/tools/build_mc_qa.py. Do not edit by hand.

"""

# Article titles that are wiki meta pages rather than game facts.
SKIP_TITLES = {
    "Feature", "Structure file", "Terrain features", "Block variant",
    "Client request placeholder block", "Deprecated Anvil", "Deny", "Allow",
    "Border", "Border block", "Cursor", "Highlight", "Debug fourj item",
    "Debug Stick", "Dupe Hack", "Displacement Wand", "Fire Wand",
    "MCRedstoneSim schematics", "Build allow block", "Build disallow block",
    "Dimension Control", "Item (entity)", "Block Inspector",
}


def clean(text):
    text = text.replace("\u00a0", " ")
    text = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]+)\]\]", r"\1", text)
    text = re.sub(r"\{\{[^{}]*\}\}", " ", text)
    text = re.sub(r"\[[0-9]+\]", "", text)
    text = re.sub(r"File:[^.\n]+", " ", text)
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


def paragraphs(block):
    out = []
    for p in re.split(r"\n\s*\n", block):
        p = clean(p)
        if not p:
            continue
        if p.startswith("==") or p.startswith("|") or p.startswith("{"):
            continue
        # Drop table rows, image captions, and short fragments.
        if len(p) < 80 or len(p) > 1600:
            continue
        if p.count("|") > 4:
            continue
        out.append(p)
    return out


def sentences(text, limit=3):
    parts = re.split(r"(?<=[.!?])\s+", text)
    out = []
    for s in parts:
        s = s.strip()
        if not s:
            continue
        out.append(s)
        if len(out) >= limit:
            break
    return " ".join(out)


def split_sections(text):
    """Return (intro, {lowercased heading: body}) for one article."""
    chunks = re.split(r"(?m)^(={2,4})\s*([^=\n]+?)\s*\1\s*$", text)
    intro = chunks[0]
    sections = {}
    for i in range(1, len(chunks) - 1, 3):
        heading = chunks[i + 1].strip().lower()
        body = chunks[i + 2]
        if heading not in sections:
            sections[heading] = body
    return intro, sections


def pick_section(sections, names):
    for name in names:
        for heading, body in sections.items():
            if name in heading:
                ps = paragraphs(body)
                if ps:
                    return ps[0]
    return None


def article_pairs(title, text):
    if title in SKIP_TITLES:
        return []
    lower = title.lower()
    intro, sections = split_sections(text)
    intro_ps = paragraphs(intro)
    if not intro_ps:
        return []

    pairs = []
    definition = sentences(intro_ps[0], 3)
    if definition:
        pairs.append(("what is %s" % lower, definition))
        pairs.append(("tell me about %s" % lower, definition))
        # Keep article names natural in the answer even when the extract starts
        # with a pronoun or a wiki-specific phrase.
        pairs.append(("describe %s" % lower, definition))

    usage = pick_section(sections, ["usage", "behavior", "uses"])
    if usage:
        u = sentences(usage, 3)
        pairs.append(("what does %s do" % lower, u))
        pairs.append(("what is %s used for" % lower, u))
        pairs.append(("how do i use %s" % lower, u))

    obtaining = pick_section(sections, ["obtaining", "natural generation", "source", "acquisition"])
    if obtaining:
        o = sentences(obtaining, 3)
        pairs.append(("how do i get %s" % lower, o))
        pairs.append(("how do i obtain %s" % lower, o))
        pairs.append(("where do i find %s" % lower, o))

    crafting = pick_section(sections, ["crafting", "recipe"])
    if crafting:
        c = sentences(crafting, 3)
        pairs.append(("how do i craft %s" % lower, c))
        pairs.append(("what is the recipe for %s" % lower, c))

    # Drop duplicate answers for the same article so the corpus stays varied.
    seen = set()
    out = []
    for q, a in pairs:
        a = re.sub(r"\s+", " ", a).strip()
        if len(a) < 40 or (q, a) in seen:
            continue
        seen.add((q, a))
        out.append((q, a))
    return out


def main():
    if not os.path.exists(SRC):
        sys.stderr.write("missing %s; run fetch_minecraft_wiki.py first\n" % SRC)
        return 1
    text = open(SRC, encoding="utf-8").read()
    articles = re.split(r"(?m)^===== (.+?) =====\s*$", text)
    total = 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(HEADER)
        for i in range(1, len(articles) - 1, 2):
            title = articles[i].strip()
            body = articles[i + 1]
            for q, a in article_pairs(title, body):
                f.write("user: %s\n" % q)
                f.write("ultron: %s\n\n" % a)
                total += 1
    print("wrote %s: %d pairs, %d bytes" % (OUT, total, os.path.getsize(OUT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
